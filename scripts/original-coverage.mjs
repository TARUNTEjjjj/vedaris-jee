// Chapter/concept coverage map for original practice, counted in families
// with a recorded independent audit, never in random seeds or variants.
//
//   node scripts/original-coverage.mjs          print the map
//   node scripts/original-coverage.mjs --write  refresh docs/ORIGINAL-PRACTICE.md
//   node scripts/original-coverage.mjs --check  fail if the document is stale
import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { resolve } from 'node:path';
import { CHAPTERS, SUBJECTS, listTemplates } from '../src/questions/index.js';
import { ORACLES } from './original-oracle.mjs';

const DOC = fileURLToPath(new URL('../docs/ORIGINAL-PRACTICE.md', import.meta.url));
const START = '<!-- coverage:start (generated by scripts/original-coverage.mjs) -->';
const END = '<!-- coverage:end -->';

// Audits that already existed for the first 30 families, in tests/core.test.mjs.
// Statement recovery re-derives the numerical key from the stem in floating
// point (tolerance 1e-9); key-text checks confirm the keyed option text.
const STATEMENT_RECOVERY = new Set(['phy-projectile-v1', 'phy-atwood-v1', 'phy-work-spring-v1', 'phy-collision-v1', 'phy-capacitors-v1', 'phy-circuit-v1', 'phy-lens-v1', 'phy-photoelectric-v1',
  'chem-limiting-v1', 'chem-hydrogen-v1', 'chem-gas-v1', 'chem-hess-v1', 'chem-kc-v1', 'chem-electrolysis-v1', 'chem-first-order-v1', 'chem-colligative-v1',
  'math-roots-v1', 'math-complex-v1', 'math-ap-v1', 'math-binomial-v1', 'math-probability-v1', 'math-matrix-v1', 'math-integral-v1', 'math-vectors-v1']);
const KEY_TEXT_CHECK = new Set(['phy-shm-v1', 'phy-orbit-v1', 'chem-neutralisation-v1', 'chem-isomers-v1', 'math-conic-v1', 'math-optimisation-v1']);

export function auditKind(templateId) {
  if (Object.hasOwn(ORACLES, templateId)) return 'exact-oracle';
  if (STATEMENT_RECOVERY.has(templateId)) return 'statement-recovery';
  if (KEY_TEXT_CHECK.has(templateId)) return 'key-text-check';
  return null;
}

/** Per-chapter map. A family counts only if it has a recorded audit. */
export function originalCoverage() {
  const families = listTemplates();
  const chapters = CHAPTERS.map(chapter => {
    const own = families.filter(family => family.chapter === chapter.id);
    const audited = own.filter(family => auditKind(family.id));
    const linked = families.filter(family => family.chapter !== chapter.id && family.concepts.includes(chapter.id));
    return { id: chapter.id, subject: chapter.subject, title: chapter.title, families: own.map(f => f.id), auditedFamilies: audited.map(f => f.id), audits: audited.map(f => auditKind(f.id)), linkedFrom: linked.map(f => f.id) };
  });
  const audited = families.filter(family => auditKind(family.id));
  return {
    familyCount: families.length,
    auditedFamilyCount: audited.length,
    exactOracleFamilyCount: audited.filter(family => auditKind(family.id) === 'exact-oracle').length,
    multiConceptFamilyCount: families.filter(family => family.kind === 'multi-concept').length,
    chapterCount: chapters.length,
    coveredChapterCount: chapters.filter(chapter => chapter.auditedFamilies.length).length,
    gaps: chapters.filter(chapter => !chapter.auditedFamilies.length).map(chapter => chapter.id),
    chapters,
  };
}

const label = { 'exact-oracle': 'exact oracle', 'statement-recovery': 'statement recovery', 'key-text-check': 'key-text check' };
export function coverageMarkdown(map = originalCoverage()) {
  const lines = [
    `${map.familyCount} original families, ${map.auditedFamilyCount} with a recorded audit (${map.exactOracleFamilyCount} by the exact oracle). ${map.coveredChapterCount} of ${map.chapterCount} chapters have at least one audited family; ${map.gaps.length} remain gaps. Seeds and variants are not counted.`,
    '',
    '| Subject | Chapter | Own families (audit) | Also exercised by |',
    '| --- | --- | --- | --- |',
  ];
  for (const subject of SUBJECTS) for (const chapter of map.chapters.filter(row => row.subject === subject.id)) {
    const own = chapter.families.length ? chapter.families.map(id => `\`${id}\` (${label[auditKind(id)] || 'unaudited'})`).join('<br>') : '**Gap**';
    lines.push(`| ${subject.title} | ${chapter.title} | ${own} | ${chapter.linkedFrom.map(id => `\`${id}\``).join('<br>') || '—'} |`);
  }
  return lines.join('\n');
}

export function replaceCoverage(document, markdown = coverageMarkdown()) {
  const start = document.indexOf(START), end = document.indexOf(END);
  if (start === -1 || end < start) throw new Error('Coverage markers are missing from docs/ORIGINAL-PRACTICE.md');
  return `${document.slice(0, start + START.length)}\n${markdown}\n${document.slice(end)}`;
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const mode = process.argv[2];
  if (!mode) console.log(coverageMarkdown());
  else {
    const current = await readFile(DOC, 'utf8');
    const next = replaceCoverage(current);
    if (mode === '--write') await writeFile(DOC, next);
    else if (mode === '--check' && next !== current) { console.error('docs/ORIGINAL-PRACTICE.md coverage is stale. Run node scripts/original-coverage.mjs --write'); process.exitCode = 1; }
  }
}
