import { mkdir, readFile, readdir, rm, writeFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import { execFileSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';
import { dirname, join, resolve } from 'node:path';
import { validateArchive, archiveStats } from '../src/archive/index.js';
import { prepareContent } from './build-content.mjs';

const projectRoot = fileURLToPath(new URL('../', import.meta.url));
const digest = bytes => createHash('sha256').update(bytes).digest('hex');
const MAX_FILE_BYTES = 5 * 1024 * 1024;
const MAX_RELEASE_BYTES = 15 * 1024 * 1024;
async function walk(root, directory) {
  const results = [];
  for (const item of (await readdir(join(root, directory), {withFileTypes: true})).sort((a, b) => a.name.localeCompare(b.name, 'en'))) {
    const path = `${directory}/${item.name}`;
    if (item.isSymbolicLink()) throw new Error(`Release inputs must not contain symlinks: ${path}`);
    if (item.isDirectory()) results.push(...await walk(root, path));
    else if (item.isFile()) results.push(path);
  }
  return results;
}

/** A release serves only its own verified shell/assets; normal SW lifecycle protects active tabs. */
export function serviceWorkerSource({version, files, shell}) {
  return `// Generated by Vedaris. No skipWaiting or clients.claim: updates wait for old tabs to close.
const VERSION = ${JSON.stringify(version)};
const SCOPE = self.registration.scope;
const CACHE_PREFIX = 'vedaris-static:' + SCOPE + ':';
const CACHE = CACHE_PREFIX + VERSION;
const SHELL = new URL(${JSON.stringify(shell)}, SCOPE).href;
const FILES = new Map(Object.entries(${JSON.stringify(files)}).map(([path, hash]) => [new URL(path, SCOPE).href, hash]));
const ROOT = new URL(SCOPE);
async function verifiedFetch(url) {
  const response = await fetch(new Request(url, {cache: 'reload', credentials: 'same-origin', redirect: 'error'}));
  if (!response.ok || response.redirected) throw new Error('Release asset unavailable: ' + url);
  const actual = Array.from(new Uint8Array(await crypto.subtle.digest('SHA-256', await response.clone().arrayBuffer()))).map(byte => byte.toString(16).padStart(2, '0')).join('');
  if (actual !== FILES.get(url)) throw new Error('Release asset digest mismatch: ' + url);
  return response;
}
self.addEventListener('install', event => event.waitUntil((async () => {
  const cache = await caches.open(CACHE);
  try {
    // Fetch and verify the complete release before writing anything to its cache.
    const responses = await Promise.all([...FILES.keys()].map(async url => [url, await verifiedFetch(url)]));
    await Promise.all(responses.map(([url, response]) => cache.put(url, response)));
  } catch (error) { await caches.delete(CACHE); throw error; }
})()));
self.addEventListener('activate', event => event.waitUntil((async () => {
  const keys = await caches.keys();
  await Promise.all(keys.filter(key => key.startsWith(CACHE_PREFIX) && key !== CACHE).map(key => caches.delete(key)));
})()));
async function releaseAsset(url) {
  const cache = await caches.open(CACHE);
  const cached = await cache.match(url);
  if (cached) return cached;
  const response = await verifiedFetch(url);
  await cache.put(url, response.clone());
  return response;
}
self.addEventListener('fetch', event => {
  if (event.request.method !== 'GET') return;
  const url = new URL(event.request.url);
  if (url.origin !== ROOT.origin) return;
  if (event.request.mode === 'navigate') {
    // Hash routes live at the root document. Never cache error pages or unrelated navigations.
    if (url.pathname !== ROOT.pathname && url.pathname !== ROOT.pathname + 'index.html') return;
    event.respondWith(releaseAsset(SHELL).catch(() => new Response('Vedaris is unavailable offline on this device. Reconnect and reload.', {status: 503, headers: {'Content-Type': 'text/plain; charset=utf-8', 'Cache-Control': 'no-store'}})));
    return;
  }
  // Requests for another release pass through, never answered by a stale cross-cache match.
  if (FILES.has(url.href)) event.respondWith(releaseAsset(url.href));
});
`;
}

function versionHtml(html, prefix) {
  return html.replace(/((?:src|href)=["'])((?:assets|src|data)\/[^"']+)(["'])/g, (_, before, path, after) => `${before}${prefix}/${path}${after}`)
    .replace(/(href=["'])manifest\.webmanifest(["'])/g, `$1${prefix}/manifest.webmanifest$2`);
}

export async function buildSite(root = projectRoot) {
  root = resolve(root);
  const archive = JSON.parse(await readFile(join(root, 'data/archive.json'), 'utf8'));
  const errors = validateArchive(archive);
  if (errors.length) throw new Error(errors.join('\n'));
  const assets = await walk(root, 'assets');
  const content = await prepareContent(root, archive, assets);
  const publicInputs = [...await walk(root, 'src'), ...assets, 'data/archive.json', ...content.inputs.keys()].sort();
  if (new Set(publicInputs).size !== publicInputs.length) throw new Error('Duplicate release input path');
  const inputs = new Map();
  for (const path of [...publicInputs, 'index.html', 'manifest.webmanifest', '_headers', '404.html'].sort()) {
    const bytes = content.inputs.get(path) ?? await readFile(join(root, path));
    if (bytes.length > MAX_FILE_BYTES) throw new Error(`Release input exceeds 5 MiB budget: ${path}`);
    inputs.set(path, bytes);
  }
  if ([...inputs.values()].reduce((sum, bytes) => sum + bytes.length, 0) > MAX_RELEASE_BYTES) throw new Error('Release exceeds 15 MiB offline budget');
  for (const path of publicInputs.filter(path => path.endsWith('.js'))) execFileSync(process.execPath, ['--check', join(root, path)], {stdio: 'pipe'});
  const inputHashes = Object.fromEntries([...inputs].map(([path, bytes]) => [path, digest(bytes)]));
  // Builder changes also version the release, including service-worker policy changes.
  inputHashes['@builder'] = digest(await readFile(fileURLToPath(import.meta.url)));
  const version = digest(JSON.stringify(inputHashes)).slice(0, 20);
  const prefix = `releases/${version}`;
  const output = join(root, 'dist');
  await rm(output, {recursive: true, force: true});
  await mkdir(join(output, prefix), {recursive: true});
  const emitted = new Map();
  async function emit(path, bytes) {
    await mkdir(dirname(join(output, path)), {recursive: true});
    await writeFile(join(output, path), bytes);
    emitted.set(path, digest(bytes));
  }
  for (const path of publicInputs) await emit(`${prefix}/${path}`, inputs.get(path));
  const html = versionHtml(inputs.get('index.html').toString('utf8'), prefix);
  await emit('index.html', html);
  // Served as the root response by the worker, so its relative asset URLs resolve at scope root.
  await emit(`${prefix}/index.html`, html);
  const originalManifest = JSON.parse(inputs.get('manifest.webmanifest').toString('utf8'));
  const manifest = {...originalManifest, id: '../../', start_url: '../../', scope: '../../'};
  await emit(`${prefix}/manifest.webmanifest`, `${JSON.stringify(manifest)}\n`);
  const rootManifest = {...originalManifest, icons: originalManifest.icons?.map(icon => ({...icon, src: `${prefix}/${icon.src}`}))};
  await emit('manifest.webmanifest', `${JSON.stringify(rootManifest)}\n`);
  // Cloudflare serves this at arbitrary missing paths; absolute links still reach site assets/home.
  const notFound = versionHtml(inputs.get('404.html').toString('utf8'), `/${prefix}`).replace(/(href=["'])\.\/(["'])/g, '$1/$2');
  await emit('404.html', notFound);
  const sourceHeaders = inputs.get('_headers').toString('utf8');
  // Preserve security headers. Mutable entry points revalidate; release URLs are immutable.
  const headers = `${sourceHeaders.trimEnd()}\n\n/releases/*\n  Cache-Control: public, max-age=31536000, immutable\n/\n  Cache-Control: no-cache\n/index.html\n  Cache-Control: no-cache\n/manifest.webmanifest\n  Cache-Control: no-cache\n/build-info.json\n  Cache-Control: no-cache\n/sw.js\n  Cache-Control: no-cache\n/404.html\n  Cache-Control: no-cache\n`;
  await emit('_headers', headers);
  // Pages redirects index.html to its directory URL. Hash the emitted bytes but request
  // their canonical URL so redirect:error remains a valid integrity safeguard.
  const precache = Object.fromEntries([...emitted].filter(([path]) => path.startsWith(`${prefix}/`)).map(([path, hash]) => [path.endsWith('/index.html') ? path.slice(0, -'index.html'.length) : path, hash]).sort(([a], [b]) => a.localeCompare(b, 'en')));
  const sw = serviceWorkerSource({version, files: precache, shell: `${prefix}/`});
  await emit('sw.js', sw);
  const bytes = [...inputs.values()].reduce((sum, buffer) => sum + buffer.length, 0);
  const info = {version, release: prefix, sourceBytes: bytes, precacheFiles: Object.keys(precache).length, files: Object.fromEntries([...emitted].sort(([a], [b]) => a.localeCompare(b, 'en'))), coverage: archiveStats(archive), playableContent: content.counts};
  await writeFile(join(output, 'build-info.json'), `${JSON.stringify(info, null, 2)}\n`);
  return info;
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const info = await buildSite();
  console.log(`Built Vedaris ${info.version}: ${info.precacheFiles} immutable release assets; ${info.coverage.paperCount} source records. External PDFs and staged imports are excluded.`);
}
