// Report usable coverage and the remaining historical gaps from the reviewed
// bank, the source catalog and the import plan. Nothing here is estimated.
//
//   node scripts/import-plan-status.mjs           # print the status block
//   node scripts/import-plan-status.mjs --write   # refresh it in docs/HISTORICAL-IMPORT-PLAN.md
//   node scripts/import-plan-status.mjs --check   # fail if the committed block is stale
import { readFile, writeFile } from 'node:fs/promises';
import { join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { planReadiness, validateImportPlan } from './import-plan.mjs';

const root = fileURLToPath(new URL('../', import.meta.url));
const DOC = 'docs/HISTORICAL-IMPORT-PLAN.md';
const START = '<!-- import-plan-status:start -->';
const END = '<!-- import-plan-status:end -->';

export async function renderStatus(base = root) {
  const read = async path => JSON.parse(await readFile(join(base, path), 'utf8'));
  const archive = await read('data/archive.json');
  const plan = await read('content/historical-import-plan.json');
  const errors = validateImportPlan(plan, archive);
  if (errors.length) throw new Error(errors.join('\n'));
  const catalog = await read('content/catalog.json');
  const playable = new Map();
  for (const {path} of catalog.bundles) for (const question of (await read(path)).questions) playable.set(question.year, (playable.get(question.year) ?? 0) + 1);
  const complete = new Set(catalog.papers.map(paper => paper.paperId));
  const years = [...new Set(archive.papers.map(paper => paper.year))].sort((a, b) => a - b);
  const historical = years.filter(year => year < plan.policy.appliesBeforeYear);
  const official = historical.filter(year => archive.papers.some(paper => paper.year === year && paper.coverage === 'full-paper'));
  const partial = historical.filter(year => !official.includes(year));
  const lines = [START, '', `Generated by \`node scripts/import-plan-status.mjs --write\` from the plan dated ${plan.updatedAt}.`, ''];
  lines.push(`- **Playable now:** ${[...playable.values()].reduce((a, b) => a + b, 0)} reviewed questions from ${complete.size} complete papers, years ${[...playable.keys()].sort().join(', ')}.`);
  lines.push(`- **Historical years not playable:** ${historical.length} (${historical[0]}–${historical.at(-1)}). Playable historical questions: ${historical.reduce((sum, year) => sum + (playable.get(year) ?? 0), 0)}.`);
  lines.push(`- **Catalogued as official full papers but untranscribed:** ${official.length} years (${official[0]}–${official.at(-1)}).`);
  lines.push(`- **Only partial or third-party collections catalogued:** ${partial.length} years (${partial[0]}–${partial.at(-1)}). These cannot complete a paper.`);
  lines.push('', '| Tranche paper | Stage | Questions referenced / staged | Certification | Publication blockers | Full-mock blockers |', '| --- | --- | ---: | --- | ---: | ---: |');
  for (const record of plan.papers) {
    const readiness = planReadiness(plan, archive, record.paperId);
    lines.push(`| ${record.paperId} | ${record.stage} | ${readiness.counts.referenced} / ${readiness.counts.staged + readiness.counts.published} | ${readiness.certification} | ${readiness.publication.length} | ${readiness.mock.length} |`);
  }
  for (const record of plan.papers) {
    const readiness = planReadiness(plan, archive, record.paperId);
    lines.push('', `**${record.paperId}: what still blocks a full mock**`, '', ...readiness.mock.map(blocker => `- ${blocker}`));
  }
  lines.push('', END);
  return lines.join('\n');
}

async function main() {
  const status = await renderStatus();
  const args = process.argv.slice(2);
  if (!args.length) { console.log(status); return; }
  const path = join(root, DOC);
  const doc = await readFile(path, 'utf8');
  const start = doc.indexOf(START), end = doc.indexOf(END);
  if (start < 0 || end < start) throw new Error(`${DOC} has no status markers`);
  const next = doc.slice(0, start) + status + doc.slice(end + END.length);
  if (args[0] === '--write') { await writeFile(path, next); console.log(`Updated ${DOC}`); }
  else if (args[0] === '--check') { if (next !== doc) { console.error(`${DOC} is stale. Run node scripts/import-plan-status.mjs --write`); process.exitCode = 1; } }
  else throw new Error('Usage: node scripts/import-plan-status.mjs [--write|--check]');
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) await main();
